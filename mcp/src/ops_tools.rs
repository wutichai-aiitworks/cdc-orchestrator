//! Operations tools: latency (ADR 0016), notification channels and deliveries (ADR 0015),
//! audit and pipeline logs, plus a catalog of every documented `/cdc` operation and generic
//! read / write calls so an agent can reach anything the orchestrator does (ADR 0017).
//!
//! Pipelines can be named instead of passing a UUID (`resolve_pipeline`).

