// WireGuard tunnels (ADR 0010): sites whose databases are not exposed are reached through the
// cdc-wireguard gateway. Connections pick a tunnel with `tunnel_id`; the orchestrator rewrites them
// to a gateway forward at run and test time.

export type TunnelStatus = {
  connected: boolean
  handshake_age_secs?: number | null
  last_handshake?: string | null
  rx_bytes: number
  tx_bytes: number
  resolved_endpoint?: string
  forwards: { host: string; port: number; listen_port: number; active_connections: number }[]
}

export type WireguardTunnel = {
  id: string
  name: string
  address: string
  private_key: string
  public_key: string
  dns: string[]
  mtu?: number | null
  peer_endpoint: string
  peer_public_key: string
  preshared_key: string
  site_address: string
  allowed_ips: string[]
  keepalive?: number | null
  notes: string
  created_at: string
  updated_at: string
  status?: TunnelStatus | null
}

export type SiteConfig = { config: string; complete?: boolean; listen_port: number; gateway_tunnel_ip: string; site_tunnel_address: string; checklist: string[] }

export type TunnelSaveResult = WireguardTunnel & {
  /** Secrets generated by this save, shown once (site_private_key, preshared_key). */
  once?: { site_private_key?: string; preshared_key?: string }
  site?: SiteConfig
  gateway_error?: string
}

// Shared across every connection editor on the page: one fetch, refreshed on demand.
const cache = ref<{ configured: boolean; gateway_reachable: boolean; tunnels: WireguardTunnel[] } | null>(null)
let inflight: Promise<any> | null = null

export const useWireguard = () => {
  const fetchTunnels = async (force = false) => {
    if (cache.value && !force) return cache.value
    inflight ??= $fetch<{ configured: boolean; gateway_reachable: boolean; tunnels: WireguardTunnel[] }>("/api/cdc/wireguard/tunnels")
      .then((r) => (cache.value = r))
      .catch(() => (cache.value = { configured: false, gateway_reachable: false, tunnels: [] }))
      .finally(() => (inflight = null))
    return inflight
  }
  const createTunnel = (body: Record<string, any>) =>
    $fetch<TunnelSaveResult>("/api/cdc/wireguard/tunnels", { method: "POST", body }).finally(() => fetchTunnels(true))
  const updateTunnel = (id: string, body: Record<string, any>) =>
    $fetch<TunnelSaveResult>(`/api/cdc/wireguard/tunnels/${encodeURIComponent(id)}`, { method: "PUT", body }).finally(() => fetchTunnels(true))
  const deleteTunnel = (id: string) =>
    $fetch(`/api/cdc/wireguard/tunnels/${encodeURIComponent(id)}`, { method: "DELETE" }).finally(() => fetchTunnels(true))
  const fetchSiteConfig = (id: string) => $fetch<SiteConfig>(`/api/cdc/wireguard/tunnels/${encodeURIComponent(id)}/site-config`)
  /** New site keys: the gateway switches over, and the complete site wg0.conf comes back once. */
  const rotateSiteKeys = (id: string, presharedKey = true) =>
    $fetch<TunnelSaveResult>(`/api/cdc/wireguard/tunnels/${encodeURIComponent(id)}/site-keys`, { method: "POST", body: { preshared_key: presharedKey } })
  const probe = (id: string, host: string, port: number) =>
    $fetch<{ ok: boolean; ms?: number; error?: string; hint?: string; connected?: boolean; target: string }>(
      `/api/cdc/wireguard/tunnels/${encodeURIComponent(id)}/probe`,
      { method: "POST", body: { host, port } },
    )
  const tunnelName = (id?: string | null) => (id ? cache.value?.tunnels.find((t) => t.id === id)?.name || "a deleted tunnel" : "")
  return { tunnels: cache, fetchTunnels, createTunnel, updateTunnel, deleteTunnel, fetchSiteConfig, rotateSiteKeys, probe, tunnelName }
}
